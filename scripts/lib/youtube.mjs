import { fetchJson, fetchText } from './http.mjs';

// Candidates stored per song (fallback if embedding is forbidden)
const MAX_CANDIDATES = 4;
// Beyond this deviation from the Spotify length a video counts as a different version
const DURATION_TOLERANCE_S = 12;

const UNWANTED = /\b(live|cover|remix|sped ?up|slowed|reverb|nightcore|8d|karaoke|instrumental|acoustic|theatre version|1 hour|loop|reaction|tutorial)\b/i;

const parseDuration = (text) =>
  text ? text.split(':').reduce((sum, part) => sum * 60 + Number(part), 0) : Number.NaN;

// ISO 8601 duration from the Data API (PT3M44S) in seconds
const parseIsoDuration = (iso) => {
  const m = iso?.match(/PT(?:(\d+)H)?(?:(\d+)M)?(?:(\d+)S)?/);
  return m ? Number(m[1] ?? 0) * 3600 + Number(m[2] ?? 0) * 60 + Number(m[3] ?? 0) : Number.NaN;
};

const normalize = (s) => s.toLowerCase().normalize('NFKD').replace(/[^\p{L}\p{N} ]/gu, ' ');

// Scores how well a video matches the Spotify track (higher = better)
function score(video, track) {
  const target = track.durationMs / 1000;
  const diff = Math.abs(video.seconds - target);
  const title = normalize(video.title);
  const channel = normalize(video.channel);
  const mainArtist = normalize(track.artist.split(',')[0]);
  let s = 0;

  s += Number.isFinite(diff) ? Math.max(0, 40 - diff * 2) : 0;
  if (diff > DURATION_TOLERANCE_S) s -= 40;
  if (title.includes(normalize(track.title).trim())) s += 20;
  if (channel.endsWith(' topic')) s += 25; // Audio auto-generated by YouTube = studio version
  if (channel.includes(mainArtist.trim())) s += 15;
  if (/official (audio|video)|audio/.test(title)) s += 8;
  if (UNWANTED.test(video.title) && !UNWANTED.test(track.title)) s -= 60;
  return s;
}

// Official YouTube Data API v3 (needs YOUTUBE_API_KEY)
async function searchWithApi(query, key) {
  const params = new URLSearchParams({ part: 'snippet', type: 'video', videoEmbeddable: 'true', maxResults: '10', q: query, key });
  const search = await fetchJson(`https://www.googleapis.com/youtube/v3/search?${params}`);
  const ids = search.items.map((i) => i.id.videoId).filter(Boolean);
  if (ids.length === 0) return [];
  const details = await fetchJson(
    `https://www.googleapis.com/youtube/v3/videos?${new URLSearchParams({ part: 'contentDetails,snippet', id: ids.join(','), key })}`,
  );
  return details.items.map((v) => ({
    id: v.id,
    title: v.snippet.title,
    channel: v.snippet.channelTitle,
    seconds: parseIsoDuration(v.contentDetails.duration),
  }));
}

// Without API key: read results from the public search page (best effort)
async function searchWithoutApi(query) {
  const html = await fetchText(`https://www.youtube.com/results?search_query=${encodeURIComponent(query)}&sp=EgIQAQ%253D%253D`);
  const match = html.match(/var ytInitialData = (\{.*?\});<\/script>/s);
  if (!match) return [];
  const results = [];
  (function walk(node) {
    if (!node || typeof node !== 'object') return;
    const v = node.videoRenderer;
    if (v?.videoId) {
      results.push({
        id: v.videoId,
        title: v.title?.runs?.[0]?.text ?? '',
        channel: v.ownerText?.runs?.[0]?.text ?? '',
        seconds: parseDuration(v.lengthText?.simpleText),
      });
    }
    for (const key in node) walk(node[key]);
  })(JSON.parse(match[1]));
  return results;
}

// Finds matching YouTube videos for a track, best first
export async function findVideos(track, apiKey) {
  const query = `${track.artist.split(',')[0]} ${track.title}`;
  const results = apiKey ? await searchWithApi(query, apiKey) : await searchWithoutApi(query);
  const unique = [...new Map(results.map((r) => [r.id, r])).values()];
  return unique
    .map((video) => ({ video, score: score(video, track) }))
    .filter((r) => r.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, MAX_CANDIDATES)
    .map((r) => r.video);
}
